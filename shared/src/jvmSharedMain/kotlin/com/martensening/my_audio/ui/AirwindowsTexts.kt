package com.martensening.my_audio.ui

import androidx.compose.runtime.Composable
import androidx.compose.runtime.State
import androidx.compose.runtime.produceState
import com.martensening.my_audio.audio.AirwindowsCatalog
import com.martensening.my_audio.audio.AirwindowsEffect
import com.martensening.my_audio.resources.Res
import com.martensening.my_audio.resources.allStringResources
import org.jetbrains.compose.resources.StringResource
import org.jetbrains.compose.resources.getString
import org.jetbrains.compose.resources.stringResource

/**
 * The app's own one-line descriptions of the Airwindows effects in the current language
 * (resources `airwindows.xml`, generated by tools/airwindows_texts.py); the English original
 * from the catalog is the fallback.
 */
object AirwindowsTexts {
    /** Must match `resource_key` in tools/airwindows_texts.py. */
    fun key(name: String) = "aw_" + name.lowercase().replace(Regex("[^a-z0-9]"), "_")

    fun resource(name: String): StringResource? = Res.allStringResources[key(name)]
}

@Composable
fun airwindowsDescription(effect: AirwindowsEffect): String =
    AirwindowsTexts.resource(effect.name)?.let { stringResource(it) } ?: effect.description

/** All descriptions by effect name, loaded once in the background; empty until ready. */
@Composable
fun rememberAirwindowsDescriptions(): State<Map<String, String>> = produceState(emptyMap()) {
    value = AirwindowsCatalog.effects.associate { effect ->
        effect.name to (AirwindowsTexts.resource(effect.name)?.let { getString(it) } ?: effect.description)
    }
}
