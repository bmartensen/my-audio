"""Prepare the My Audio branding assets from the preserved masters.

Raster preparation lives in prepare_branding.py. This file retains the native geometry for the
theme-coloured silhouette, which must stay simple at small sizes. Git preserves the previous design.

Usage:  .venv\\Scripts\\python.exe tools\\generate_icon.py
All coordinates use the 108 x 108 adaptive-icon viewport; the visible safe zone is a circle of radius 33.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app" / "src" / "main" / "res"

MONOCHROME = "#FF000000"

# Keyboard: seven white keys, black keys after C, D, F, G and A.
KEY_LEFT, KEY_WIDTH, KEY_GAP = 29.5, 7.0, 0.4
KEY_TOP, KEY_BOTTOM, BLACK_BOTTOM = 60.0, 76.0, 70.0
BLACK_HALF_WIDTH = 2.2
WHITE_KEYS = [(KEY_LEFT + KEY_WIDTH * i + KEY_GAP, KEY_LEFT + KEY_WIDTH * (i + 1) - KEY_GAP) for i in range(7)]
BLACK_KEYS = [(KEY_LEFT + KEY_WIDTH * i - BLACK_HALF_WIDTH, KEY_LEFT + KEY_WIDTH * i + BLACK_HALF_WIDTH)
              for i in (1, 2, 4, 5, 6)]

# Microphone: capsule, U-shaped holder and stem down to the keyboard.
CAPSULE = (46.0, 22.0, 62.0, 46.0)
CAPSULE_RADIUS = 8.0
GRILLE_LINES = (30.0, 34.0, 38.0)
GRILLE_LEFT, GRILLE_RIGHT, GRILLE_HALF = 48.5, 59.5, 0.75
HOLDER_CENTER, HOLDER_RADIUS, STROKE = (54.0, 38.0), 13.0, 3.0
STEM = (52.5, 50.0, 55.5, KEY_TOP)


def fmt(value):
    return f"{value:g}"


def rounded_rect_path(x0, y0, x1, y1, tl=0.0, tr=0.0, br=0.0, bl=0.0):
    def arc(r, x, y):
        return f"A{fmt(r)},{fmt(r)} 0 0 1 {fmt(x)},{fmt(y)}" if r else f"L{fmt(x)},{fmt(y)}"

    return (f"M{fmt(x0 + tl)},{fmt(y0)} H{fmt(x1 - tr)} {arc(tr, x1, y0 + tr)} "
            f"V{fmt(y1 - br)} {arc(br, x1 - br, y1)} H{fmt(x0 + bl)} {arc(bl, x0, y1 - bl)} "
            f"V{fmt(y0 + tl)} {arc(tl, x0 + tl, y0)} Z")


def holder_path():
    cx, cy = HOLDER_CENTER
    r = HOLDER_RADIUS
    # Lower half circle from left to right (counter-clockwise on screen).
    return f"M{fmt(cx - r)},{fmt(cy)} A{fmt(r)},{fmt(r)} 0 0 0 {fmt(cx + r)},{fmt(cy)}"


def capsule_path():
    return rounded_rect_path(*CAPSULE, CAPSULE_RADIUS, CAPSULE_RADIUS, CAPSULE_RADIUS, CAPSULE_RADIUS)


def grille_paths():
    h = GRILLE_HALF
    return [rounded_rect_path(GRILLE_LEFT, y - h, GRILLE_RIGHT, y + h, h, h, h, h) for y in GRILLE_LINES]


def vector(paths, header_comment):
    body = "\n".join(paths)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {header_comment} Generated by tools/generate_icon.py; edit the script instead. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{body}
</vector>
"""


def fill(path, color, even_odd=False):
    rule = '\n        android:fillType="evenOdd"' if even_odd else ""
    return f'    <path\n        android:fillColor="{color}"{rule}\n        android:pathData="{path}" />'


def stroke(path, color):
    return (f'    <path\n        android:strokeColor="{color}"\n        android:strokeWidth="{fmt(STROKE)}"\n'
            f'        android:strokeLineCap="round"\n        android:pathData="{path}" />')


def monochrome_xml():
    # Black keys and grille lines become holes so the silhouette keeps its detail.
    keyboard = " ".join([rounded_rect_path(WHITE_KEYS[0][0], KEY_TOP, WHITE_KEYS[-1][1], KEY_BOTTOM, br=1.5, bl=1.5)]
                        + [rounded_rect_path(x0, KEY_TOP, x1, BLACK_BOTTOM, br=1, bl=1) for x0, x1 in BLACK_KEYS])
    capsule = " ".join([capsule_path()] + grille_paths())
    paths = [
        fill(rounded_rect_path(*STEM), MONOCHROME),
        stroke(holder_path(), MONOCHROME),
        fill(keyboard, MONOCHROME, even_odd=True),
        fill(capsule, MONOCHROME, even_odd=True),
    ]
    return vector(paths, "My Audio themed-icon silhouette.")


def main():
    drawable = RES / "drawable"
    (drawable / "ic_launcher_monochrome.xml").write_text(monochrome_xml(), encoding="utf-8")
    from prepare_branding import main as prepare
    prepare()


if __name__ == "__main__":
    main()
