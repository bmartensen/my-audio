"""Writes the English and German one-line descriptions of the Airwindows effects as app resources.

Source is tools/airwindows_texts.tsv (name, corrected English, German), maintained by hand; the
originals stay in the vendored catalog (AirwindowsCatalog.inc) and the app shows them on request.
The script fails unless every catalog effect has exactly one complete row.

    .venv\\Scripts\\python.exe tools\\airwindows_texts.py
"""
import csv
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TABLE = REPO / 'tools' / 'airwindows_texts.tsv'
CATALOG = REPO / 'app' / 'src' / 'main' / 'cpp' / 'third_party' / 'airwindows' / 'AirwindowsCatalog.inc'
RESOURCES = REPO / 'shared' / 'src' / 'commonMain' / 'composeResources'


def resource_key(name: str) -> str:
    """Must match `AirwindowsTexts.key` in the app."""
    return 'aw_' + re.sub(r'[^a-z0-9]', '_', name.lower())


def android_string(text: str) -> str:
    text = text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    return text.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"')


def main() -> None:
    catalog = re.findall(r'^    X\((\w+), ', CATALOG.read_text(encoding='ascii'), re.MULTILINE)
    with TABLE.open(encoding='utf-8', newline='') as file:
        rows = list(csv.DictReader(file, delimiter='\t', quoting=csv.QUOTE_NONE))
    names = [row['name'] for row in rows]
    problems = []
    if len(set(names)) != len(names):
        problems.append('duplicate names: ' + ', '.join(sorted({n for n in names if names.count(n) > 1})))
    if missing := sorted(set(catalog) - set(names)):
        problems.append('missing: ' + ', '.join(missing))
    if extra := sorted(set(names) - set(catalog)):
        problems.append('not in the catalog: ' + ', '.join(extra))
    for row in rows:
        if not row.get('english') or not row.get('german') or None in row:
            problems.append(f'incomplete row: {row.get("name")}')
    keys = [resource_key(n) for n in names]
    if len(set(keys)) != len(keys):
        problems.append('resource keys collide')
    if problems:
        raise SystemExit('\n'.join(problems))

    for folder, column in (('values', 'english'), ('values-de', 'german')):
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 '<!-- Generated by tools/airwindows_texts.py from tools/airwindows_texts.tsv; do not edit. -->',
                 '<resources>']
        lines += [f'    <string name="{resource_key(row["name"])}">{android_string(row[column])}</string>'
                  for row in sorted(rows, key=lambda r: r['name'].lower())]
        lines += ['</resources>', '']
        (RESOURCES / folder / 'airwindows.xml').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'{len(rows)} descriptions in English and German')


if __name__ == '__main__':
    main()
