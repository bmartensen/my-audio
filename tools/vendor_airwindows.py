"""Copies the Airwindows effects for the effect library from an airwin2rack checkout.

Only MIT-licensed sources from airwin2rack's `src/` are taken: the plugin base and, per kept
effect, `<Name>.h`, `<Name>.cpp` and `<Name>Proc.cpp`. The script writes them to
app/src/main/cpp/third_party/airwindows together with a generated catalog
(`AirwindowsCatalog.inc`) and records the source commit in README.md. Running it again with
another checkout replaces the whole folder, so the pinned version is always exactly one commit.

    git clone https://github.com/baconpaul/airwin2rack.git <dir>
    .venv\\Scripts\\python.exe tools\\vendor_airwindows.py <dir>
"""
import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TARGET = REPO / 'app' / 'src' / 'main' / 'cpp' / 'third_party' / 'airwindows'

# Technically unsuitable before the fixed loudness stage and the Opus export (see the wiki):
# word-length reducers, mix-check and metering tools, clocks, control voltages and monitoring helpers.
EXCLUDED_CATEGORIES = {'Dithers'}
EXCLUDED_EFFECTS = {
    'PeaksOnly', 'SlewOnly', 'SubsOnly',              # mix checks
    'Monitoring', 'Monitoring2', 'Monitoring3',       # monitoring with dither and check modes
    'SoftClock', 'SoftClock2', 'SoftClock3',          # time references
    'DCVoltage',                                      # a DC control voltage
    'ContentHideD',                                   # mutes audio except for glimpses
    'VoiceTrick',                                     # live monitoring trick while recording
}

STRING = r'"((?:[^"\\]|\\.)*)"'
ENTRY = re.compile(r'registerAirwindow\(\{' + STRING + r', ' + STRING + r', (-?\d+), (true|false), ' + STRING
                   + r', [^,]+, ' + STRING + r', .*\{([^}]*)\}\}\);')

# Typographic characters of the original texts, folded to ASCII for C++ sources and JNI.
ASCII = {'‘': "'", '’': "'", '“': '\\"', '”': '\\"', '–': '-', '—': '-',
         '…': '...', ' ': ' ', '\u0093': '\\"', '\u0094': '\\"', '\u0092': "'"}


def clean(text: str) -> str:
    for old, new in ASCII.items():
        text = text.replace(old, new)
    return ''.join(c if ord(c) < 128 else '?' for c in text)


def main(source: Path) -> None:
    src = source / 'src'
    raw = (src / 'ModuleAdd.h').read_bytes()
    # Some texts carry Windows-1252 quotes; decode those bytes instead of failing.
    text = raw.decode('utf-8', errors='surrogateescape')
    text = ''.join(bytes([ord(c) - 0xDC00]).decode('cp1252', errors='replace') if 0xDC80 <= ord(c) <= 0xDCFF else c
                   for c in text)
    entries = []
    for line in text.splitlines():
        if 'registerAirwindow' not in line:
            continue
        match = ENTRY.search(line)
        if not match:
            raise SystemExit(f'Unparsed registry line: {line[:120]}')
        name, category, _, _, what, _, _ = match.groups()
        # The registry itself skips effects without a description.
        if not what or category in EXCLUDED_CATEGORIES or name in EXCLUDED_EFFECTS:
            continue
        entries.append((name, category, clean(what)))
    entries.sort(key=lambda e: e[0].lower())

    commit = subprocess.run(['git', '-C', str(source), 'rev-parse', 'HEAD'], capture_output=True, text=True,
                            check=True).stdout.strip()
    # Empty the folder file by file (an open shell or IDE may hold the directories themselves).
    if TARGET.exists():
        for path in sorted(TARGET.rglob('*'), reverse=True):
            if path.is_file():
                path.unlink()
    effects = TARGET / 'autogen_airwin'
    effects.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source / 'LICENSE.md', TARGET / 'LICENSE.md')
    for base in ('airwin_consolidated_base.h', 'airwin_consolidated_base.cpp'):
        shutil.copy2(src / base, TARGET / base)
    for name, _, _ in entries:
        for suffix in ('.h', '.cpp', 'Proc.cpp'):
            shutil.copy2(src / 'autogen_airwin' / f'{name}{suffix}', effects / f'{name}{suffix}')

    # Some headers define configuration macros (e.g. THREEBYTHREE) that would leak into the next
    # header of this single translation unit; reset them before every include.
    macros = set()
    for name, _, _ in entries:
        for match in re.finditer(r'^#define (\w+)', (effects / f'{name}.h').read_text(encoding='utf-8', errors='replace'),
                                 re.MULTILINE):
            if not match.group(1).startswith('__'):
                macros.add(match.group(1))
    lines = [f'// Generated by tools/vendor_airwindows.py from airwin2rack {commit}; do not edit.',
             '// X(Name, "Category", "Original one-line description"), sorted by name.', '#pragma once', '']
    for name, _, _ in entries:
        lines += [f'#undef {macro}' for macro in sorted(macros)]
        lines.append(f'#include "autogen_airwin/{name}.h"')
    lines += [f'#undef {macro}' for macro in sorted(macros)]
    lines += ['', '#define AIRWINDOWS_CATALOG(X) \\']
    lines += [f'    X({name}, "{category}", "{what}") \\' for name, category, what in entries]
    lines += ['', '']
    (TARGET / 'AirwindowsCatalog.inc').write_text('\n'.join(lines), encoding='ascii', newline='\n')

    (TARGET / 'CMakeLists.txt').write_text(
        '# Airwindows effects of the effect library (MIT, see LICENSE.md); generated by tools/vendor_airwindows.py.\n'
        '# Always optimised but without fast math, so the effects sound exactly like the originals.\n'
        'file(GLOB AIRWINDOWS_SOURCES CONFIGURE_DEPENDS ${CMAKE_CURRENT_SOURCE_DIR}/autogen_airwin/*.cpp)\n'
        'add_library(airwindows STATIC ${CMAKE_CURRENT_SOURCE_DIR}/airwin_consolidated_base.cpp ${AIRWINDOWS_SOURCES})\n'
        'target_include_directories(airwindows PUBLIC ${CMAKE_CURRENT_SOURCE_DIR})\n'
        'set_target_properties(airwindows PROPERTIES POSITION_INDEPENDENT_CODE ON)\n'
        'if(MSVC)\n'
        '    target_compile_options(airwindows PRIVATE /W0 /O2 /utf-8)\n'
        '    target_compile_definitions(airwindows PRIVATE _USE_MATH_DEFINES NOMINMAX _CRT_SECURE_NO_WARNINGS)\n'
        'else()\n'
        '    target_compile_options(airwindows PRIVATE -w -O2)\n'
        'endif()\n', encoding='ascii', newline='\n')

    categories = sorted({c for _, c, _ in entries})
    (TARGET / 'README.md').write_text(
        '# Airwindows (vendored)\n\n'
        f'Source: https://github.com/baconpaul/airwin2rack, commit `{commit}`, files from `src/` only '
        '(MIT, see LICENSE.md; Airwindows by Chris Johnson, consolidated by Paul Walker).\n\n'
        f'{len(entries)} effects in {len(categories)} categories. Left out: category Dithers and '
        + ', '.join(sorted(EXCLUDED_EFFECTS)) + '.\n\n'
        'Regenerate with `tools/vendor_airwindows.py <airwin2rack checkout>`; do not edit by hand.\n',
        encoding='ascii', newline='\n')
    print(f'{len(entries)} effects in {len(categories)} categories from {commit}')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(Path(sys.argv[1]).resolve())
